static void oled_draw_char(unsigned char *fb, int x, int y, char c) {
    if (c < 32 || c > 126 || x >= 128 || y >= 8) return;
    int font_idx = c - 32;
    for (int i = 0; i < 5; i++) {
        if (x + i < 128) {
            fb[y * 128 + x + i] = font5x7[font_idx][i];
        }
    }
}

static void oled_draw_string(unsigned char *fb, const char *str) {
    int x = 0;
    int y = 0;
    while (*str) {
        if (*str == '\n') {
            y++;
            x = 0;
        } else {
            oled_draw_char(fb, x, y, *str);
            x += 6; // 5 width + 1 space
            if (x >= 128) {
                x = 0;
                y++;
            }
        }
        if (y >= 8) break; // Screen full
        str++;
    }
}

static bool hw_oled_print_execute(nc_tool *self, const char *args_json, char *out, size_t out_cap) {
    char text[256] = {0};

    char *text_str = strstr(args_json, "\"text\":\"");
    if (text_str) {
        text_str += 8;
        char *end = strchr(text_str, '"');
        if (end) {
            int len = end - text_str;
            if (len >= (int)sizeof(text)) len = sizeof(text) - 1;
            memcpy(text, text_str, len);
        }
    }

    int file;
    if ((file = open("/dev/i2c-1", O_RDWR)) < 0) {
        nc_strlcpy(out, "{\"error\": \"Failed to open /dev/i2c-1\"}", out_cap);
        return true;
    }

    if (ioctl(file, I2C_SLAVE, OLED_ADDR) < 0) {
        close(file);
        nc_strlcpy(out, "{\"error\": \"Failed to bind to OLED I2C address 0x3C\"}", out_cap);
        return true;
    }

    /* Full SSD1306 Initialization sequence */
    unsigned char init_seq[] = {
        0x00, /* Command stream */
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14,
        0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1,
        0xDB, 0x40, 0xA4, 0xA6, 0xAF
    };
    if (write(file, init_seq, sizeof(init_seq)) < 0) {
        close(file);
        nc_strlcpy(out, "{\"error\": \"Failed to initialize display\"}", out_cap);
        return true;
    }

    /* Reset addressing to top-left before sending data */
    unsigned char addr_seq[] = {0x00, 0x21, 0, 127, 0x22, 0, 7};
    write(file, addr_seq, sizeof(addr_seq));

    /* 1024 byte framebuffer + 1 byte for 0x40 data prefix */
    unsigned char *fb_cmd = calloc(1, 1025);
    if (fb_cmd) {
        fb_cmd[0] = 0x40; /* Data prefix */
        oled_draw_string(fb_cmd + 1, text); /* Render text into fb */
        write(file, fb_cmd, 1025); /* Flush entire screen over I2C */
        free(fb_cmd);
    }

    close(file);

    snprintf(out, out_cap, "{\"status\": \"success\", \"text_displayed\": \"%s\"}", text);
    return true;
}

nc_tool nc_tool_hw_oled(void) {
    nc_tool tool = {
        .def = {
            .name = "hw_oled_print",
            .description = "Prints text to the SSD1306 OLED display via I2C.",
            .parameters_json = "{\"type\":\"object\",\"properties\":{\"text\":{\"type\":\"string\",\"description\":\"Text to display\"}},\"required\":[\"text\"]}"
        },
        .execute = hw_oled_print_execute,
        .free = NULL
    };
    return tool;
}
